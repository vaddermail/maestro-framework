#!/usr/bin/env bash
# _meta/verify.sh — the framework's own gate ("Gates, not gut feelings", MANIFESTO.md §7).
# Checks Maestro's internal consistency. Run from the framework root or from anywhere
# (the script repositions itself). Exits with code 1 on failures — serves as a gate in CI
# or in playbooks/add-an-agent.md.
# Line-ending guard: a copy with CRLF (Windows) failed with cryptic errors and the gate never ran.
# The `#` at the end of the next line makes it immune to the very \r it detects.
case "$(head -c 4000 "$0")" in *$'\r'*) printf '✗ %s has CRLF line endings — restore with git checkout (the copy .gitattributes prevents the conversion) or: sed -i "s/\\r$//" %s\n' "$0" "$0"; exit 2 ;; esac #
set -uo pipefail
cd "$(dirname "$0")/.."
# Deterministic locale: under LC_ALL=C, [^[:alnum:]] matches the bytes of accented characters and
# "§Sess" resolved against "## Sessão"; CI runs C.UTF-8 — the gate must give the same answer
# everywhere.
if locale -a 2>/dev/null | grep -qiE '^C\.utf-?8$'; then export LC_ALL=C.UTF-8; fi

# --integrity mode (--integridade also accepted): compares the local copy against the
# release manifest (_meta/SHA256SUMS, generated by the upstream release.yml). Detects
# silent drift from the "the copy is read-only" rule in any session, without waiting
# for the sync.
# Exits 0 (intact), 1 (diverges) or 2 (NOT VERIFIABLE: no checksum tool on PATH — a red
# light about something nobody looked at is as dishonest as a green one).
case "${1:-}" in
  --integrity|--integridade) : ;;
  --*) printf '✗ unknown flag: %s (did you mean --integrity?)\n' "${1}"; exit 1 ;;
  *) ;;
esac
if [ "${1:-}" = "--integrity" ] || [ "${1:-}" = "--integridade" ]; then
  if [ ! -f _meta/SHA256SUMS ]; then
    printf '✗ no _meta/SHA256SUMS manifest (this is a working clone, not a release ZIP)\n'
    exit 1
  fi
  if command -v sha256sum >/dev/null 2>&1; then somas='sha256sum'
  elif command -v shasum >/dev/null 2>&1; then somas='shasum -a 256'
  else
    printf -- '— integrity: NOT VERIFIABLE (no sha256sum or shasum on PATH — install coreutils)\n'
    exit 2
  fi
  # `-c` only looks at what is listed: an EXTRA file inside the copy (a local note, an invented
  # spec) passed as "identical". Extras are drift just as much as edits are.
  extras=$(comm -13 <(awk '{print $2}' _meta/SHA256SUMS | sort) \
                   <(find . -type f ! -path './.git/*' ! -path './_meta/SHA256SUMS' | sed 's|^\./||' | sort))
  if [ -z "$extras" ] && $somas -c --quiet _meta/SHA256SUMS 2>/dev/null; then
    printf '✓ integrity: the copy is identical to the origin release.\n'
    exit 0
  else
    [ -n "$extras" ] && { printf '✗ integrity: file(s) that do not come from the release:\n'; printf '%s\n' "$extras" | head -10; }
    printf '✗ integrity: the copy DIVERGES from the origin release — every difference is a local edit\n'
    printf '  to reconcile (playbooks/sync-framework.md step 3) and, almost always, an entry\n'
    printf '  for the project FRAMEWORK-IMPROVEMENTS.md.\n'
    printf '  If ALL files fail on a Windows machine, it is Git CRLF conversion: restore the copy\n'
    printf '  (git checkout -- Maestro/) with the copy .gitattributes already in the repository.\n'
    $somas -c _meta/SHA256SUMS 2>/dev/null | grep -v ': OK$' | head -20
    exit 1
  fi
fi

# Any other argument is a typo, not a mode: without this guard, `verify.sh --integrit`
# (or `xyz`) fell through to the default sweep and printed "Framework consistent" with exit 0 —
# a gate printing green about a mode that never ran.
if [ -n "${1:-}" ]; then
  printf '✗ unknown argument: %s\n' "$1"
  printf '  Usage: verify.sh [--integrity]\n'
  exit 1
fi

falhas=0
falha() { printf '✗ %s\n' "$*"; falhas=$((falhas + 1)); }
ok() { printf '✓ %s\n' "$*"; }

# A file that is legitimately cited but legitimately absent from a distributed copy:
# it is listed in _meta/DO-NOT-DISTRIBUTE. Absent AND listed is not a break — it is
# the confidentiality lever working. (The integrity manifest is one such case.)
upstream_only() {
  [ "$1" = "_meta/SHA256SUMS" ] && return 0
  [ -f _meta/DO-NOT-DISTRIBUTE ] || return 1
  while IFS= read -r l; do
    case "$l" in '' | \#*) continue ;; esac
    case "$1" in $l) return 0 ;; esac
  done < _meta/DO-NOT-DISTRIBUTE
  return 1
}

# Distributable tree = tracked files + new ones not yet added (honouring .gitignore); without
# git, the disk outside .git. A file created mid-session and not yet `git add`ed is the most
# common case — and it was invisible to check 14 (which only saw `git ls-files`), while check 2
# counted even what .gitignore declares temporary. Both checks now share one notion of
# "what gets distributed".
lista_alvos() {
  if command -v git >/dev/null 2>&1 && git rev-parse --git-dir >/dev/null 2>&1; then
    git -c core.quotePath=false ls-files --cached --others --exclude-standard
  fi | grep . || find . -type f -not -path './.git/*' | sed 's|^\./||'
}

# The agent specs (excludes READMEs, the template and the derived CONTRACTS.md)
fichas() { find agents -mindepth 2 -type f -name '*.md' ! -name 'README.md' ! -name 'AGENT-TEMPLATE.md' ! -name 'CONTRACTS.md'; }

