# ---------------------------------------------------------------------------
# 14. Forbidden-terms sweep: no real name travels inside the copies.
#     Provenance travels by project CODENAME (knowledge/candidates.md §Entry and
#     exit rules, rule 5) — client names, product names and stacks never do.
#     Case-insensitive (one entry catches every capitalization — the case-sensitive version
#     let 15 occurrences of one term travel), sweeps file NAMES too, and never prints the
#     term itself (only its line number in the list): CI logs get distributed as well.
#     The list ships empty on purpose: add your own terms, and list the populated
#     file in _meta/DO-NOT-DISTRIBUTE so the list itself does not travel either.
# ---------------------------------------------------------------------------
if [ ! -f _meta/FORBIDDEN-TERMS ]; then
  printf -- '— forbidden-terms sweep: NOT APPLICABLE (no _meta/FORBIDDEN-TERMS)\n'
else
  alvos=$(lista_alvos | grep -v '^_meta/FORBIDDEN-TERMS$')
  ter_ko=0; i=0; n_termos=0
  while IFS= read -r termo; do
    i=$((i + 1))
    case "$termo" in '' | \#*) continue ;; esac
    n_termos=$((n_termos + 1))
    # -H: with a single file grep omitted the name and the cut printed the content (the term);
    # -e: a term starting with "-" is not an option. The file name is printed only down to its
    # folder when the name itself contains the term.
    while IFS= read -r hit; do
      [ -n "$hit" ] || continue
      f=${hit%%:*}; ln=${hit#*:}
      if printf '%s' "$(basename "$f")" | grep -qiE -e "$termo"; then hit="$(dirname "$f")/[name-with-term]:$ln"; fi
      falha "FORBIDDEN TERM (term no. $i in the list) in $hit"
      ter_ko=1
    done < <(printf '%s\n' "$alvos" | tr '\n' '\0' | xargs -0 grep -niHE -e "$termo" 2>/dev/null | cut -d: -f1,2)
    while IFS= read -r nome; do
      [ -n "$nome" ] || continue
      falha "FORBIDDEN TERM (term no. $i in the list) in the NAME of a file under $(dirname "$nome")/"
      ter_ko=1
    done < <(printf '%s\n' "$alvos" | grep -iE -e "$termo")
  done < _meta/FORBIDDEN-TERMS
  if [ "$n_termos" -eq 0 ]; then
    printf -- '— forbidden-terms sweep: no terms configured (see _meta/FORBIDDEN-TERMS)\n'
  elif [ "$ter_ko" -eq 0 ]; then
    ok "forbidden-terms sweep: no real name in what gets distributed"
  fi
fi

# ---------------------------------------------------------------------------
# 15. Internal § citations in templates: by NAME, never by number.
#     A `§8` pointing inside its own file breaks silently the day a section is
#     inserted — that is how 1.0.3 started sending old sessions into the
#     technical-debt section. `§Name` is immune to renumbering.
#     (A `§N` attached to a backticked path is an external reference to another
#     file's numbered item — legitimate, and governed by check 8.)
# ---------------------------------------------------------------------------
sec_ko=0
while IFS= read -r f; do
  while IFS=: read -r n texto; do
    printf '%s' "$texto" | grep -qE '`[^`]+\.md` *§[0-9]' && continue
    falha "SELF-REFERENTIAL §N CITATION: $f:$n — use §Section name (immune to renumbering)"
    sec_ko=1
  done < <(grep -nE '§[0-9]' "$f")
done < <(find templates -type f -name '*.template' | sort)
[ "$sec_ko" -eq 0 ] && ok "§ citations in templates: by name, not by number"

# ---------------------------------------------------------------------------
# 16–18. Mandatory skeletons for loops, modules and workflows — declared in the folder
#     READMEs since 1.0 and never verified. A loop without an anti-infinite safeguard is
#     the one addition that can set an agent iterating without a ceiling; a workflow
#     without "Decision points" loses the mandatory human approval. Same mechanics as check 12.
# ---------------------------------------------------------------------------
lp_ko=0
while IFS= read -r f; do
  prev=0
  for s in '## Identification' '## Progress metric' '## Entry condition' '## Action' '## Exit condition' '## Anti-infinite-loop safeguard' '## STATE.md record' '## Related'; do
    ln=$(grep -nF "$s" "$f" | head -1 | cut -d: -f1)
    [ -n "$ln" ] || { falha "LOOP MISSING SECTION '$s': $f (loops/README.md — the safeguard is mandatory)"; lp_ko=1; continue; }
    [ "$ln" -ge "$prev" ] || { falha "LOOP WITH SECTIONS OUT OF ORDER: $f ('$s')"; lp_ko=1; }
    prev=$ln
  done
done < <(find loops -type f -name 'L*.md')
[ "$lp_ko" -eq 0 ] && ok "loops: mandatory skeleton present (with anti-infinite safeguard)"

md_ko=0
while IFS= read -r f; do
  for s in '## The problem it solves' '## The model' '## Non-negotiable rules' '## How to adopt it in a new product' '## Variations and trade-offs' '## Example' '## Known pitfalls' '## Related'; do
    grep -qF "$s" "$f" || { falha "MODULE MISSING SECTION '$s': $f (modules/README.md §Common skeleton)"; md_ko=1; }
  done
done < <(find modules -type f -name '*.md' ! -name 'README.md')
[ "$md_ko" -eq 0 ] && ok "modules: mandatory skeleton present"

wf_ko=0
while IFS= read -r f; do
  for s in '## Objective' '## Steps' '## Decision points' '## Loops it opens' '## Related'; do
    grep -qF "$s" "$f" || { falha "WORKFLOW MISSING SECTION '$s': $f (workflows/README.md §Structure)"; wf_ko=1; }
  done
  grep -qiE '^## .*preconditions' "$f" || { falha "WORKFLOW WITHOUT PRECONDITIONS: $f"; wf_ko=1; }
  grep -qiE '^## (Exit gate|Closing condition)' "$f" || { falha "WORKFLOW WITHOUT AN EXIT GATE/CLOSING CONDITION: $f"; wf_ko=1; }
done < <(find workflows -type f -name 'W*.md')
[ "$wf_ko" -eq 0 ] && ok "workflows: common anatomy present (steps, decisions, loops, gate)"

