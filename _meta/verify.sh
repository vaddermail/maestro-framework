# ---------------------------------------------------------------------------
# 8. § anchors: every `file` §Section reference points to an existing heading.
#    Tolerant of trailing prose (shortens the anchor word by word), but the match is
#    ANCHORED at the START of the heading (optional numbering stripped) — the previous
#    version degraded into "the first word is a substring of any heading" and approved
#    §Gate P99 against "Anatomy of a gate". Section labels (§A, §3) must be a heading's
#    label; item IDs (A1, C4, FR-12, AR-7) only need to exist as a token.
#    Second pass: anchors to the project's LIVE files (STATE.md, CLAUDE.md,
#    FRAMEWORK-IMPROVEMENTS.md) resolve against the headings of the matching template —
#    it was the absence of this gate that let 23 citations of a non-existent §Debt through.
# ---------------------------------------------------------------------------
titulos_de() { grep -E '^#{1,6} ' "$1" | sed -E 's/^#+ +//; s/\*\*//g; s/^([0-9]+(\.[0-9]+)*[.)]?|[A-Z][.)]) +([—–-] +)?//'; }
# Strict mode (live files: few headings, and short): the anchor must START with a complete
# heading — "per-block consumption record" does not resolve against "Record history" just by
# sharing the first word; "Done (Cost of AI field" resolves because it starts with "Done".
resolve_estrito() { # $1 = target  $2 = anchor
  local t esc
  while IFS= read -r t; do
    [ -n "$t" ] || continue
    t=$(printf '%s' "$t" | sed -E 's/ *\(.*$//; s/ *[—–-] .*$//; s/ *$//')
    esc=$(printf '%s' "$t" | sed 's/[][\\.*^$(){}+?|]/\\&/g')
    printf '%s' "$2" | grep -qiE "^${esc}([^[:alnum:]]|$)" && return 0
  done < <(titulos_de "$1")
  return 1
}
resolve_ancora() { # $1 = target file  $2 = anchor (without §)  $3 = optional 'estrito' → 0 if it resolves
  local alvo="$1" s="$2" esc prim titulos
  [ "${3:-}" = estrito ] && { resolve_estrito "$alvo" "$s"; return $?; }
  titulos=$(titulos_de "$alvo")
  while [ -n "$s" ]; do
    esc=$(printf '%s' "$s" | sed 's/[][\\.*^$(){}+?|]/\\&/g')
    printf '%s\n' "$titulos" | grep -qiE "^${esc}([^[:alnum:]]|$)" && return 0
    if printf '%s' "$s" | grep -qE '^([A-Z]|[0-9]+)$' && grep -qE "^#{1,6} +${s}[.)] " "$alvo"; then return 0; fi
    local novo="${s% *}"; [ "$novo" = "$s" ] && break; s="$novo"
  done
  prim=${2%% *}
  if printf '%s' "$prim" | grep -qE '^[A-Za-z]{1,3}-?[0-9]+$' && grep -qE "(^|[^A-Za-z0-9])${prim}([^A-Za-z0-9]|$)" "$alvo"; then return 0; fi
  return 1
}
# "§A / §B" and "§AR-2/§AR-18" are several anchors in one: after the first, only the parts
# starting with § count (in "§Lessons / post-mortems", "post-mortems" is prose)
resolve_composta() { # $1 = target  $2 = anchor(s)  $3 = optional 'estrito'  → 0 if all resolve
  local primeira=1 uma
  while IFS= read -r uma; do
    uma=$(printf '%s' "$uma" | sed 's/^ *//; s/ *$//')
    if [ "$primeira" -eq 1 ]; then primeira=0; else case "$uma" in §*) ;; *) continue ;; esac; fi
    uma=${uma#§}
    [ -n "$uma" ] || continue
    case "$uma" in [0-9]* | rule* | Rule* | regra* | Regra*) continue ;; esac   # §N/§rule N refer to numbered list items, not headings
    resolve_ancora "$1" "$uma" "${3:-}" || return 1
  done < <(printf '%s\n' "$2" | tr '/' '\n')
  return 0
}
anc_ko=0
while IFS='|' read -r alvo sec; do
